CREATE TABLE IF NOT EXISTS USR (
    CODE  VARCHAR(10) PRIMARY KEY,
    NOM   VARCHAR(80) NOT NULL,
    ROLE  VARCHAR(3)  NOT NULL
);

CREATE TABLE IF NOT EXISTS MBR (
    ID           INT AUTO_INCREMENT PRIMARY KEY,
    NO_MBR       VARCHAR(10) NOT NULL,
    NOM          VARCHAR(60) NOT NULL,
    PRENOM       VARCHAR(60) NOT NULL,
    DT_ADH       DATE NOT NULL,
    REV_ANN      DOUBLE,
    DETTES_MENS  DOUBLE,
    COTE         INT,
    TYP          VARCHAR(3) DEFAULT 'REG'
);

CREATE TABLE IF NOT EXISTS TAUX_REF (
    DUREE_MAX  INT PRIMARY KEY,
    TAUX       DOUBLE NOT NULL
);

CREATE TABLE IF NOT EXISTS DMD (
    ID       INT AUTO_INCREMENT PRIMARY KEY,
    MBR_ID   INT NOT NULL,
    MNT      DOUBLE NOT NULL,
    DUREE    INT NOT NULL,
    TAUX     DOUBLE,
    PMT      DOUBLE,
    FRAIS    DOUBLE DEFAULT 0,
    STATUT   VARCHAR(3) NOT NULL,
    CRT_BY   VARCHAR(10),
    CRT_DT   TIMESTAMP,
    SOU_DT   TIMESTAMP,
    DEC_BY   VARCHAR(10),
    DEC_DT   TIMESTAMP,
    MOTIF    VARCHAR(200)
);
